"""Testbench for HLS compiler: built from the same datapath + FSM plans as hls_design.
Steps it like the button; in each FSM state checks the units the FSM selects,
after each press checks the registers the FSM writes (all through sel/view)."""
from __future__ import annotations

from hls.gen_tools.datapath import DatapathPlan
from hls.gen_tools.fsm_ctrl import FSMPlan
from hls.gen_tools.verilog_gen import view_slots, _SWITCH_GROUPS, _HARDCODED_VALUE

OPS = {"+": lambda x, y: x + y, "-": lambda x, y: x - y, "*": lambda x, y: x * y}
TEST_INPUTS = [(1, 2, 3, 4), (7, 7, 7, 7), (0, 0, 0, 0), (3, 0, 5, 2)]   # in0..in3 settings

HEADER = [
    "// generated by hlsc: presses step like the button, checks each unit and register through sel/view",
    "module testbench;",
    "    reg clk = 0, reset = 1, en = 0;",
    "    reg [2:0] in0 = 0, in1 = 0, in2 = 0, in3 = 0;",
    "    reg [3:0] sel = 0;",
    "    wire [15:0] view;",
    "    wire [4:0] state;",
    "    wire done;",
    "    integer errors = 0;",
    "    hls_design dut (.clk(clk), .reset(reset), .en(en), .in0(in0), .in1(in1), .in2(in2), .in3(in3),",
    "                    .sel(sel), .view(view), .state(state), .done(done));",
    "    always #5 clk = ~clk;",
    "",
    "    // one button press: state must hold without en, then move to next on one en pulse",
    "    task step(input [4:0] next);",
    "        reg [4:0] before;",
    "        begin",
    "            before = state;",
    "            repeat (3) @(negedge clk);",
    "            if (state !== before) begin errors = errors + 1; $display(\"FAIL  state moved without a press\"); end",
    "            @(negedge clk) en = 1;",
    "            @(negedge clk) en = 0;",
    "            if (state !== next) begin errors = errors + 1; $display(\"FAIL  state = %0d, expected %0d\", state, next); end",
    "        end",
    "    endtask",
    "",
    "    // what the display shows when the view switches are set to s",
    "    task check(input [3:0] s, input [15:0] expected, input [8*32-1:0] label);",
    "        begin",
    "            sel = s; #1;",
    "            if (view === expected) $display(\"ok    %0s = %0d\", label, view);",
    "            else begin errors = errors + 1; $display(\"FAIL  %0s = %0d, expected %0d\", label, view, expected); end",
    "        end",
    "    endtask",
    "",
    "    initial begin",
    "        #20 reset = 0;",
]

FOOTER = [
    "        if (errors == 0) $display(\"PASS: all checks match\");",
    "        else $display(\"FAILED: %0d mismatches\", errors);",
    "        $finish;",
    "    end",
    "endmodule",
]


def expected_values(datapath: DatapathPlan, vector: tuple, mask: int) -> dict[str, int]:
    # same input order as verilog_gen: in0 = first name alphabetically, extras hardcoded
    value = {name: vector[i] if i < _SWITCH_GROUPS else _HARDCODED_VALUE
             for i, name in enumerate(sorted(datapath.inputs))}
    for node in datapath.registers:                   # SSA order: operands always come first
        lhs, rhs = datapath.operation_inputs[node]
        operator = datapath.node_to_unit[node].operator
        value[node] = OPS[operator](value[lhs], value[rhs]) & mask   # hardware keeps WIDTH bits
    return value


def check_line(slot: dict, datapath: DatapathPlan, node: str, expected: int, label: str) -> str:
    # through sel/view like the board; registers past the view slots are read directly
    if node in slot:
        return f'        check({slot[node]}, {expected}, "{label}");'
    register = datapath.registers[node]
    return (f'        if (dut.{register} !== {expected}) begin errors = errors + 1; '
            f'$display("FAIL  {label} = %0d, expected {expected}", dut.{register}); end')


def generate_testbench(datapath: DatapathPlan, fsm: FSMPlan) -> str:
    mask = (1 << datapath.width) - 1
    slot = {label: index for index, (_, label) in enumerate(view_slots(datapath))}
    nodes_by_register = {register: node for node, register in datapath.registers.items()}

    lines = list(HEADER)
    for vector in TEST_INPUTS:
        value = expected_values(datapath, vector, mask)
        names = " ".join(f"{name}={value[name]}" for name in sorted(datapath.inputs))
        lines += [f"        in0 = {vector[0]}; in1 = {vector[1]}; in2 = {vector[2]}; in3 = {vector[3]};",
                  f'        $display("inputs: {names}");',
                  f"        step(1);                                   // {fsm.idle_state} -> {fsm.cycle_states.get(1, fsm.done_state)}"]

        for cycle, state in fsm.cycle_states.items():
            # in this state the FSM routes operands to these units
            for unit, node in fsm.unit_selections_by_cycle[cycle].items():
                lines.append(check_line(slot, datapath, unit, value[node], f"{state}: {unit} = {node}"))
            # press: the FSM writes these registers (state numbers: idle 0, CYCLE_k k, done latency + 1)
            lines.append(f"        step({cycle + 1});")
            for register in fsm.register_writes_by_cycle[cycle]:
                node = nodes_by_register[register]
                lines.append(check_line(slot, datapath, node, value[node], f"  {register} <- {node}"))

        lines.append(f'        if (done !== 1) begin errors = errors + 1; $display("FAIL  {fsm.done_state} not reached"); end')
        lines += [check_line(slot, datapath, node, value[node], f"output {node}") for node in datapath.outputs]
        lines.append(f"        step(0);                                   // {fsm.done_state} -> {fsm.idle_state}")

    return "\n".join(lines + FOOTER)
